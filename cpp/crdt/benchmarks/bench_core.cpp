// P2-M029: native performance baselines — fixed workloads, repeated runs,
// median + percentiles reported. These are BASELINES for later comparison
// (before/after discipline, DEC-011); they are not headline claims.
//
// Workloads:
//   1. sequential append insert (10k chars)
//   2. random-position insert (5k chars into a 10k doc)
//   3. random delete (2k deletions)
//   4. remote batch apply (20k ops)
//   5. snapshot export + import (10k-op doc)
//   6. serialized op bytes per item
//
// Build type matters: run with -DCMAKE_BUILD_TYPE=Release and record the
// build type with the results.
#include <algorithm>
#include <chrono>
#include <cstdio>
#include <random>
#include <string>
#include <vector>

#include "concord/crdt/doc.hpp"
#include "concord/crdt/serialize.hpp"

using namespace concord::crdt;
using Clock = std::chrono::steady_clock;

namespace {

double median_ms(std::vector<double>& samples) {
    std::sort(samples.begin(), samples.end());
    const std::size_t n = samples.size();
    return n % 2 == 1 ? samples[n / 2] : (samples[n / 2 - 1] + samples[n / 2]) / 2.0;
}

struct Timing {
    const char* name;
    int runs;
    std::vector<double> ms;

    explicit Timing(const char* label, int run_count = 5) : name(label), runs(run_count) {
        ms.reserve(static_cast<std::size_t>(run_count));
    }

    template <typename Fn>
    void measure(Fn&& fn) {
        const auto start = Clock::now();
        fn();
        const auto end = Clock::now();
        ms.push_back(std::chrono::duration<double, std::milli>(end - start).count());
    }

    void report(std::size_t units) const {
        auto sorted = ms;
        const double med = median_ms(sorted);
        const double ops_per_ms = static_cast<double>(units) / std::max(med, 0.0001);
        std::printf("%-38s median %8.3f ms  (%9.1f units/ms, %zu units, %d runs)\n", name, med,
                    ops_per_ms, units, runs);
    }
};

}  // namespace

int main() {
    constexpr std::size_t kAppendOps = 10'000;
    constexpr std::size_t kRandomInserts = 5'000;
    constexpr std::size_t kRandomDeletes = 2'000;
    constexpr std::size_t kBatchOps = 20'000;
    constexpr int kRuns = 5;

    // 1. Sequential append.
    {
        Timing timing("sequential append", kRuns);
        std::size_t produced = 0;
        for (int run = 0; run < kRuns; ++run) {
            Doc doc(ReplicaId{1});
            timing.measure([&] {
                for (std::size_t i = 0; i < kAppendOps; ++i) {
                    (void)doc.local_insert_text(doc.stream_size(), U'a');
                }
                produced = doc.stream_size();
            });
        }
        timing.report(produced);
    }

    // 2. Random-position insert into a large document.
    {
        Timing timing("random-position insert", kRuns);
        std::size_t produced = 0;
        for (int run = 0; run < kRuns; ++run) {
            Doc doc(ReplicaId{1});
            for (std::size_t i = 0; i < kAppendOps; ++i) {
                (void)doc.local_insert_text(doc.stream_size(), U'b');
            }
            std::mt19937 rng{42};
            std::uniform_int_distribution<std::size_t> pos(0, doc.stream_size());
            timing.measure([&] {
                for (std::size_t i = 0; i < kRandomInserts; ++i) {
                    (void)doc.local_insert_text(pos(rng), U'x');
                }
                produced = kRandomInserts;
            });
        }
        timing.report(produced);
    }

    // 3. Random delete.
    {
        Timing timing("random delete", kRuns);
        for (int run = 0; run < kRuns; ++run) {
            Doc doc(ReplicaId{1});
            for (std::size_t i = 0; i < kAppendOps; ++i) {
                (void)doc.local_insert_text(doc.stream_size(), U'c');
            }
            std::mt19937 rng{7};
            std::uniform_int_distribution<std::size_t> pos(0, doc.stream_size() - 1);
            timing.measure([&] {
                for (std::size_t i = 0; i < kRandomDeletes; ++i) {
                    if (doc.stream_size() > 1) {
                        (void)doc.local_delete(pos(rng) % doc.stream_size());
                    }
                }
            });
        }
        timing.report(kRandomDeletes);
    }

    // 4. Remote batch apply (ops generated by 3 replicas, shuffled).
    {
        Timing timing("remote batch apply", kRuns);
        std::size_t delivered = 0;
        for (int run = 0; run < kRuns; ++run) {
            std::vector<Doc> sources;
            sources.emplace_back(ReplicaId{101});
            sources.emplace_back(ReplicaId{102});
            sources.emplace_back(ReplicaId{103});
            std::vector<Operation> ops;
            for (auto& source : sources) {
                for (std::size_t i = 0; i < kBatchOps / 3; ++i) {
                    ops.push_back(source.local_insert_text(source.stream_size(), U'r'));
                }
            }
            std::mt19937 rng{99};
            std::shuffle(ops.begin(), ops.end(), rng);

            Doc doc(ReplicaId{1});
            timing.measure([&] {
                delivered = doc.apply_batch(ops);
            });
        }
        timing.report(delivered);
    }

    // 5. Snapshot export + import on a 10k-op document.
    {
        Timing timing("snapshot export", kRuns);
        std::string bytes;
        for (int run = 0; run < kRuns; ++run) {
            Doc doc(ReplicaId{1});
            for (std::size_t i = 0; i < kAppendOps; ++i) {
                (void)doc.local_insert_text(doc.stream_size(), U's');
            }
            timing.measure([&] {
                bytes = doc.export_snapshot();
            });
        }
        timing.report(1);

        Timing import_timing("snapshot import", kRuns);
        for (int run = 0; run < kRuns; ++run) {
            import_timing.measure([&] {
                Doc restored = Doc::import_snapshot(ReplicaId{2}, bytes);
                (void)restored.stream_size();
            });
        }
        import_timing.report(1);
        std::printf("%-38s snapshot bytes: %zu (for %zu items)\n", "snapshot size", bytes.size(),
                    kAppendOps);
    }

    // 6. Serialized op bytes per item.
    {
        Doc doc(ReplicaId{1});
        std::string total;
        for (std::size_t i = 0; i < 100; ++i) {
            total += serialize_operation(doc.local_insert_text(doc.stream_size(), U'q'));
        }
        std::printf("%-38s %zu bytes/op average\n", "serialized op size",
                    total.size() / 100);
    }

    return 0;
}
